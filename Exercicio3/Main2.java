package Exercicio3;

public class Main2 {
    public static void main(String[] args) {
     int a = 5;
     int b = 10;

     System.out.println("a == b: " + (a == b));
     System.out.println("a != b: " + (a != b));
     System.out.println("a > b: " + (a > b));
     System.out.println("a < b: " + (a < b));
     System.out.println("a >= b: " + (a >= b));
     System.out.println("a <= b: " + (a <= b));

     System.out.println("a == 5 && b == 10: " + (a == 5 && b == 10));
     System.out.println("a == 5 || b == 5: " + (a == 5 || b == 5));
    }    
}
